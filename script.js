const root = document.documentElement;
root.classList.add("js");
const themeToggle = document.querySelector(".theme-toggle");
const languageButtons = document.querySelectorAll("[data-lang]");
const themeMeta = document.querySelector('meta[name="theme-color"]');
const descriptionMeta = document.querySelector('meta[name="description"]');

function getStoredValue(key) {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}

function storeValue(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch {
    // The page still works when storage is unavailable.
  }
}

function applyTheme(theme) {
  const safeTheme = theme === "light" ? "light" : "dark";
  root.dataset.theme = safeTheme;
  themeMeta.setAttribute("content", safeTheme === "dark" ? "#050505" : "#f7f7f7");
  updateThemeLabel();
  storeValue("xiaotian-theme", safeTheme);
}

function updateThemeLabel() {
  const language = root.dataset.language || "zh";
  const key = root.dataset.theme === "dark" ? "themeToLight" : "themeToDark";
  themeToggle.setAttribute("aria-label", translations[language][key]);
}

function applyLanguage(language) {
  const safeLanguage = translations[language] ? language : "zh";
  const dictionary = translations[safeLanguage];

  root.dataset.language = safeLanguage;
  root.lang = safeLanguage === "zh" ? "zh-CN" : safeLanguage === "ja" ? "ja-JP" : "en";
  document.title = dictionary.documentTitle;
  descriptionMeta.setAttribute("content", dictionary.description);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-label]").forEach((element) => {
    const key = element.dataset.i18nLabel;
    if (dictionary[key]) {
      element.setAttribute("aria-label", dictionary[key]);
      element.setAttribute("title", dictionary[key]);
    }
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === safeLanguage));
  });

  updateThemeLabel();
  storeValue("xiaotian-language", safeLanguage);
}

function updateClock() {
  const language = root.dataset.language || "zh";
  const locale = language === "zh" ? "zh-CN" : language === "ja" ? "ja-JP" : "en-GB";
  const now = new Date();
  const offset = -now.getTimezoneOffset();
  const sign = offset >= 0 ? "+" : "-";
  const hours = String(Math.floor(Math.abs(offset) / 60)).padStart(2, "0");
  const minutes = String(Math.abs(offset) % 60).padStart(2, "0");

  document.getElementById("local-time").textContent = new Intl.DateTimeFormat(locale, {
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: false
  }).format(now);
  document.getElementById("timezone").textContent = `UTC${sign}${hours}:${minutes}`;
}

function initializeScrollAnimations() {
  const revealGroups = [
    [".section-index", "reveal-from-left"],
    [".section-heading", ""],
    [".about-image", "reveal-from-left"],
    [".about-copy", "reveal-from-right"],
    [".music-copy", "reveal-from-left"],
    [".player-window", "reveal-from-right"],
    [".contact-panel", ""],
    [".footer-main", ""],
    [".footer-legal", ""]
  ];

  revealGroups.forEach(([selector, direction]) => {
    document.querySelectorAll(selector).forEach((element) => {
      element.classList.add("scroll-reveal");
      if (direction) {
        element.classList.add(direction);
      }
    });
  });

  document.querySelectorAll(".photo-card").forEach((card, index) => {
    card.classList.add("scroll-reveal");
    card.style.setProperty("--reveal-delay", `${index * 90}ms`);
  });

  document.querySelectorAll(".contact-links a").forEach((link, index) => {
    link.classList.add("scroll-reveal", "reveal-from-right");
    link.style.setProperty("--reveal-delay", `${120 + index * 70}ms`);
  });

  const elements = document.querySelectorAll(".scroll-reveal");
  if (!("IntersectionObserver" in window)) {
    elements.forEach((element) => element.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) {
        return;
      }

      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  }, {
    rootMargin: "0px 0px -10%",
    threshold: 0.08
  });

  elements.forEach((element) => observer.observe(element));
}

function initializeSakanaWidget() {
  if (!window.SakanaWidget) {
    return;
  }

  const dock = document.querySelector(".sakana-dock");
  const mountPoint = document.getElementById("sakana-widget");
  const restoreButton = document.querySelector(".sakana-restore");
  const minimizeButton = document.querySelector(".sakana-minimize");
  let widget = null;

  function closeWidget() {
    if (!widget || dock.classList.contains("is-closed")) {
      return;
    }

    dock.classList.add("is-closed");
    restoreButton.hidden = false;
  }

  function restoreWidget() {
    dock.classList.remove("is-closed");
    restoreButton.hidden = true;
    window.requestAnimationFrame(() => {
      window.dispatchEvent(new Event("resize"));
    });
  }

  minimizeButton.addEventListener("click", closeWidget);
  restoreButton.addEventListener("click", restoreWidget);

  widget = new window.SakanaWidget({
    autoFit: true,
    character: "takina",
    controls: true,
    rod: true,
    draggable: true,
    stroke: {
      color: "#a8a8a8",
      width: 8
    }
  }).mount(mountPoint);
}

function initializeSakanaDockDrag() {
  const dock = document.querySelector(".sakana-dock");
  const handle = document.querySelector(".sakana-move");
  if (!dock || !handle) {
    return;
  }

  const edgeGap = 6;
  let dragOffsetX = 0;
  let dragOffsetY = 0;

  function clampPosition(left, top) {
    return {
      left: Math.min(Math.max(edgeGap, left), window.innerWidth - dock.offsetWidth - edgeGap),
      top: Math.min(Math.max(edgeGap + 24, top), window.innerHeight - dock.offsetHeight - edgeGap)
    };
  }

  function setPosition(left, top, persist = false) {
    const position = clampPosition(left, top);
    dock.style.left = `${position.left}px`;
    dock.style.top = `${position.top}px`;
    dock.style.right = "auto";
    dock.style.bottom = "auto";

    if (persist) {
      storeValue("xiaotian-sakana-position", JSON.stringify({
        x: position.left / Math.max(1, window.innerWidth - dock.offsetWidth),
        y: position.top / Math.max(1, window.innerHeight - dock.offsetHeight)
      }));
    }
  }

  const storedPosition = getStoredValue("xiaotian-sakana-position");
  if (storedPosition) {
    try {
      const position = JSON.parse(storedPosition);
      setPosition(
        position.x * Math.max(1, window.innerWidth - dock.offsetWidth),
        position.y * Math.max(1, window.innerHeight - dock.offsetHeight)
      );
    } catch {
      // Ignore invalid position data and keep the default placement.
    }
  }

  handle.addEventListener("pointerdown", (event) => {
    const rect = dock.getBoundingClientRect();
    dragOffsetX = event.clientX - rect.left;
    dragOffsetY = event.clientY - rect.top;
    dock.classList.add("is-moving");
    handle.setPointerCapture(event.pointerId);
    event.preventDefault();
  });

  handle.addEventListener("pointermove", (event) => {
    if (!handle.hasPointerCapture(event.pointerId)) {
      return;
    }
    setPosition(event.clientX - dragOffsetX, event.clientY - dragOffsetY);
  });

  function finishDrag(event) {
    if (!handle.hasPointerCapture(event.pointerId)) {
      return;
    }
    handle.releasePointerCapture(event.pointerId);
    dock.classList.remove("is-moving");
    const rect = dock.getBoundingClientRect();
    setPosition(rect.left, rect.top, true);
  }

  handle.addEventListener("pointerup", finishDrag);
  handle.addEventListener("pointercancel", finishDrag);
  window.addEventListener("resize", () => {
    const rect = dock.getBoundingClientRect();
    setPosition(rect.left, rect.top, true);
  });
}

function initializeFloatingControlsContext() {
  const controls = document.querySelector(".floating-controls");
  const heroImage = document.querySelector(".hero-art");
  if (!controls || !heroImage) {
    return;
  }

  function updateControlsStyle() {
    const controlsRect = controls.getBoundingClientRect();
    const imageRect = heroImage.getBoundingClientRect();
    const centerX = controlsRect.left + controlsRect.width / 2;
    const centerY = controlsRect.top + controlsRect.height / 2;
    const isOverImage = centerX >= imageRect.left
      && centerX <= imageRect.right
      && centerY >= imageRect.top
      && centerY <= imageRect.bottom;

    controls.classList.toggle("is-over-image", isOverImage);
  }

  updateControlsStyle();
  window.addEventListener("scroll", updateControlsStyle, { passive: true });
  window.addEventListener("resize", updateControlsStyle);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

themeToggle.addEventListener("click", () => {
  applyTheme(root.dataset.theme === "dark" ? "light" : "dark");
});

const preferredTheme = getStoredValue("xiaotian-theme")
  || (window.matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark");
const preferredLanguage = getStoredValue("xiaotian-language")
  || (navigator.language.toLowerCase().startsWith("ja") ? "ja" : navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en");

applyTheme(preferredTheme);
applyLanguage(preferredLanguage);
updateClock();
initializeScrollAnimations();
initializeSakanaWidget();
initializeSakanaDockDrag();
initializeFloatingControlsContext();
setInterval(updateClock, 1000);
document.getElementById("current-year").textContent = new Date().getFullYear();
